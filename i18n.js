  function t(key, lang = currentLang) {
    if (uiTranslations[lang] && uiTranslations[lang][key]) {
      return uiTranslations[lang][key];
    }
    if (uiTranslations[DEFAULT_LANG] && uiTranslations[DEFAULT_LANG][key]) {
      return uiTranslations[DEFAULT_LANG][key];
    }
    return key;
  }


