  function init() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && languages.some((l) => l.code === saved)) {
        currentLang = saved;
      }
    } catch (e) {
      console.warn("Storage access failed", e);
    }
    applyLanguage(currentLang);
  }

